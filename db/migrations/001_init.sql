-- 001_init.sql — TaskFlow schema v1, SQLite dialect (ADR-005)
-- Implements spec/requirements.md: Task entity

CREATE TABLE IF NOT EXISTS tasks (
    id          TEXT PRIMARY KEY,              -- UUID, generated by the backend (server-side, ADR-003)
    title       TEXT NOT NULL CHECK (length(trim(title)) >= 1 AND length(title) <= 200),
    description TEXT CHECK (description IS NULL OR length(description) <= 2000),
    status      TEXT NOT NULL DEFAULT 'todo' CHECK (status IN ('todo', 'in_progress', 'done')),
    created_at  TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
    updated_at  TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
);

-- Keep updated_at server-maintained (ADR-003)
CREATE TRIGGER IF NOT EXISTS tasks_updated_at AFTER UPDATE ON tasks
BEGIN
    UPDATE tasks SET updated_at = strftime('%Y-%m-%dT%H:%M:%fZ', 'now') WHERE id = NEW.id;
END;
